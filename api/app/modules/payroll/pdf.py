def _group(whole: int, lakh: bool) -> str:
    digits = str(whole)
    if not lakh or len(digits) <= 3:
        return f"{whole:,}"
    head, tail = digits[:-3], digits[-3:]
    parts: list[str] = []
    while len(head) > 2:
        parts.insert(0, head[-2:])
        head = head[:-2]
    if head:
        parts.insert(0, head)
    return ",".join([*parts, tail])


def amount(minor: int, currency: str, lang: str) -> str:
    unit = defaults.unit_for(currency)
    sign = "-" if minor < 0 else ""
    whole, cents = divmod(abs(minor), unit)
    text = _group(whole, currency in LAKH)
    if unit > 1 and cents:
        text += f".{cents:02d}"
    symbol = SYMBOLS.get(currency, currency + " ")
    out = f"{sign}{symbol}{text}"
    return out.translate(BN_DIGITS) if lang == "bn" else out


def number(value: float | Decimal | int, lang: str) -> str:
    text = f"{Decimal(str(value)).normalize():f}"
    return text.translate(BN_DIGITS) if lang == "bn" else text


def month_name(period: str, lang: str) -> str:
    year, month = int(period[:4]), int(period[5:])
    if lang == "bn":
        return f"{BN_MONTHS[month - 1]} {str(year).translate(BN_DIGITS)}"
    return f"{calendar.month_name[month]} {year}"


