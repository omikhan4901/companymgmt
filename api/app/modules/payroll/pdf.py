def render_html(slip: PayslipOut, *, company: str, lang: str) -> str:
    t = TEXT[lang]
    currency = slip.currency or "BDT"
    e = escape

    def label(line_code: str, english: str) -> str:
        return LINE_LABELS_BN.get(line_code, english) if lang == "bn" else english

    def rows(kind: str) -> str:
        items = [x for x in slip.lines if x.kind == kind]
        if not items:
            return f'<tr><td class="muted">{t["none"]}</td><td></td></tr>'
        return "".join(
            f"<tr><td>{e(label(x.code, x.label))}</td>"
            f'<td class="amt">{amount(x.amount, currency, lang)}</td></tr>'
            for x in items
        )

    method = t.get(slip.payment_method, slip.payment_method)
    if slip.provider:
        method = f"{method} · {slip.provider}"
    if slip.account_last4:
        method += f" ··{slip.account_last4}"
    facts = [
        (t["employee"], slip.employee_name),
        (t["code"], slip.employee_code or DASH),
        (t["department"], slip.department_name or DASH),
        (t["title"], slip.job_title or DASH),
        (t["paid_by"], method),
        (t["days"], number(slip.days_in_period, lang)),
        (t["payable"], number(slip.payable_days, lang)),
        (t["unpaid"], number(slip.unpaid_leave_days, lang)),
        (t["hours"], number(round(slip.worked_minutes / 60, 1), lang)),
        (t["overtime"], number(round(slip.overtime_minutes / 60, 1), lang)),
    ]
    fact_html = "".join(f"<div><dt>{e(k)}</dt><dd>{e(str(v))}</dd></div>" for k, v in facts)
    carried = (
        f'<p class="note">{amount(slip.carried_forward, currency, lang)} · {t["carried"]}</p>'
        if slip.carried_forward
        else ""
    )
    return f"""<!doctype html>
<html lang="{lang}"><head><meta charset="utf-8"><style>{_css()}</style></head>
<body class="{lang}">
<header>
  <div class="company">{e(company)}</div>
  <div class="doc"><div class="title">{t["payslip"]}</div>
  <div class="muted">{e(month_name(slip.period or "2000-01", lang))}</div></div>
</header>
<dl>{fact_html}</dl>
<div class="cols">
  <section><h2>{t["earnings"]}</h2><table>{rows("earning")}
    <tr class="total"><td>{t["gross"]}</td>
    <td class="amt">{amount(slip.gross, currency, lang)}</td></tr></table></section>
  <section><h2>{t["deductions"]}</h2><table>{rows("deduction")}
    <tr class="total"><td>{t["total_deductions"]}</td>
    <td class="amt">{amount(slip.deductions, currency, lang)}</td></tr></table></section>
</div>
<div class="net"><span>{t["net"]}</span><span>{amount(slip.net, currency, lang)}</span></div>
{carried}
<footer>{t["footer"]}</footer>
</body></html>"""


@cache
def _fetcher() -> Any:
    """Loads only the bundled fonts: never the network or any other file."""
    from weasyprint.urls import URLFetcher, URLFetchingError

    allowed = frozenset((FONTS / f).as_uri() for f in FONTS.iterdir() if f.suffix == ".ttf")

    class FontsOnly(URLFetcher):  # type: ignore[misc]
        def fetch(self, url: str, headers: Any = None) -> Any:
            if url not in allowed:
                raise URLFetchingError(f"Blocked resource: {url[:80]}")
            return super().fetch(url, headers)

    return FontsOnly(allowed_protocols=("file",))


def render_pdf(slip: PayslipOut, *, company: str, lang: str) -> bytes:
    from weasyprint import HTML  # imported here: it loads native libraries

    html = HTML(string=render_html(slip, company=company, lang=lang), url_fetcher=_fetcher())
    pdf: bytes = html.write_pdf()
    return pdf
